"""The shop key and everything derived from it.

The shop key is 32 random bytes generated by `remu-hub init`, kept in a
root-only file (mode 0600). It is never logged, never sent to the cloud and
never written to the outbox. Every hub secret is derived from it with
HKDF-SHA256 and a distinct `info` label, so one label never reuses another's key.
"""

from __future__ import annotations

import logging
import os
import platform
import secrets
from pathlib import Path

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

log = logging.getLogger(__name__)

KEY_BYTES = 32
INFO_PROJECTION = b"remu/template-projection/v1"
INFO_PHONE = b"remu/phone-enc/v1"
INFO_CLIPS = b"remu/clip-enc/v1"
INFO_TOKENS = b"remu/app-tokens/v1"


class KeyError_(RuntimeError):
    pass


def derive(shop_key: bytes, info: bytes, length: int = 32) -> bytes:
    return HKDF(algorithm=hashes.SHA256(), length=length, salt=None, info=info).derive(shop_key)


def create_shop_key(path: Path) -> bytes:
    """Create the shop key file if it does not exist. Returns the key."""
    if path.exists():
        return read_shop_key(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    key = secrets.token_bytes(KEY_BYTES)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "wb") as fh:
        fh.write(key)
    if platform.system() == "Linux" and os.geteuid() == 0:
        os.chown(path, 0, 0)
    elif platform.system() != "Linux" or os.geteuid() != 0:
        log.warning("shop key owned by the current user (development); on the Pi it is root-only")
    return key


def read_shop_key(path: Path) -> bytes:
    try:
        key = path.read_bytes()
    except FileNotFoundError as exc:
        raise KeyError_(f"shop key not found at {path}; run `remu-hub init`") from exc
    if len(key) != KEY_BYTES:
        raise KeyError_(f"shop key at {path} has the wrong length")
    mode = path.stat().st_mode & 0o777
    if mode & 0o077:
        raise KeyError_(f"shop key at {path} must be mode 0600, is {oct(mode)}")
    return key


class Sealer:
    """AES-256-GCM with a derived key. Output is nonce (12 bytes) followed by ciphertext."""

    def __init__(self, shop_key: bytes, info: bytes) -> None:
        self._aead = AESGCM(derive(shop_key, info))

    def seal(self, plaintext: bytes, aad: bytes = b"") -> bytes:
        nonce = secrets.token_bytes(12)
        return nonce + self._aead.encrypt(nonce, plaintext, aad)

    def open(self, blob: bytes, aad: bytes = b"") -> bytes:
        return self._aead.decrypt(blob[:12], blob[12:], aad)
